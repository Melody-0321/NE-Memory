/**
 * 构建时脚本：扫描 test-cases/ 目录，提取所有 test-case.md，
 * 生成 src/test-runner/test-data.generated.js（嵌入 test-case.md 原始内容）。
 * 在 rollup 构建前运行。
 */
var fs = require('fs');
var path = require('path');

var TEST_CASES_DIR = path.join(__dirname, '..', 'test-cases');
var OUTPUT_FILE = path.join(__dirname, '..', 'src', 'test-runner', 'test-data.generated.js');

var knownTests = [];
var markdownMap = {};

function collect(dir) {
    var entries;
    try {
        entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch (e) {
        console.warn('[gen-test-data] Warning: cannot read ' + dir + ': ' + e.message);
        return;
    }

    for (var ei = 0; ei < entries.length; ei++) {
        var entry = entries[ei];
        if (!entry.isDirectory()) continue;

        // Skip abandoned/obsolete directories
        var skipDirs = ['smartpush-group-a'];
        if (skipDirs.indexOf(entry.name) !== -1) {
            console.log('[gen-test-data] Skipping obsolete directory: ' + entry.name);
            continue;
        }

        var mdPath = path.join(dir, entry.name, 'test-case.md');
        if (!fs.existsSync(mdPath)) continue;

        var raw = fs.readFileSync(mdPath, 'utf-8');
        var name = parseName(raw, entry.name);

        if (name) {
            markdownMap[name] = raw;
            var title = parseTitle(raw, entry.name);
            knownTests.push({ name: name, title: title });
            console.log('[gen-test-data] ' + name + ' -> ' + title);
        }
    }
}

function parseName(raw, folderName) {
    var trimmed = raw.trim();
    if (trimmed.indexOf('---') === 0) {
        var end = trimmed.indexOf('---', 3);
        if (end !== -1) {
            var front = trimmed.substring(3, end);
            var lines = front.split('\n');
            for (var li = 0; li < lines.length; li++) {
                var m = lines[li].match(/^name:\s*(.+)/);
                if (m) return m[1].trim();
            }
        }
    }
    // fallback: use folder name
    return folderName;
}

function parseTitle(raw, folderName) {
    var trimmed = raw.trim();
    if (trimmed.indexOf('---') === 0) {
        var end = trimmed.indexOf('---', 3);
        if (end !== -1) {
            var front = trimmed.substring(3, end);
            var lines = front.split('\n');
            for (var li = 0; li < lines.length; li++) {
                var m = lines[li].match(/^title:\s*(.+)/);
                if (m) {
                    var t = m[1].trim();
                    if ((t.charAt(0) === '"' && t.charAt(t.length - 1) === '"') ||
                        (t.charAt(0) === "'" && t.charAt(t.length - 1) === "'")) {
                        t = t.substring(1, t.length - 1);
                    }
                    return t;
                }
            }
        }
    }
    // fallback: find first heading
    var h1m = raw.match(/^#\s+(.+)/m);
    return h1m ? h1m[1].trim() : folderName;
}

collect(TEST_CASES_DIR);

// Sort by name
knownTests.sort(function(a, b) { return a.name.localeCompare(b.name); });

var output =
    '// Auto-generated by scripts/generate-test-data.js. Do not edit.\n' +
    '// Run `npm run build` to regenerate.\n' +
    '\n' +
    'export var __KNOWN_TESTS = ' + JSON.stringify(knownTests, null, 2) + ';\n' +
    '\n' +
    'export var __TEST_MARKDOWN = ' + JSON.stringify(markdownMap, null, 2) + ';\n';

fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');
console.log('[gen-test-data] OK — ' + Object.keys(markdownMap).length + ' test cases -> ' + OUTPUT_FILE);
